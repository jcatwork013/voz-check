/** Format an ISO date / timestamp into Vietnamese locale. Empty → em-dash. */
export function fmtDateTime(value: string | undefined | null): string {
  if (!value) return '—';
  const d = new Date(value);
  if (Number.isNaN(d.getTime())) return value;
  return d.toLocaleString('vi-VN', {
    day: '2-digit',
    month: '2-digit',
    year: 'numeric',
    hour: '2-digit',
    minute: '2-digit',
  });
}

/** Relative-ish short time for compact tables. */
export function fmtShort(value: string | undefined | null): string {
  if (!value) return '—';
  const d = new Date(value);
  if (Number.isNaN(d.getTime())) return value;
  return d.toLocaleString('vi-VN', {
    day: '2-digit',
    month: '2-digit',
    hour: '2-digit',
    minute: '2-digit',
  });
}

export function fmtNumber(n: number | undefined | null): string {
  if (n === undefined || n === null) return '0';
  return n.toLocaleString('vi-VN');
}
